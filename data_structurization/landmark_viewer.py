"""Interactive viewer for inspecting extracted landmark samples.

This tool scans the ``landmarks`` directory populated by
``arabic_sign_landmarks.py`` and exposes a minimal Tkinter UI that lets you:

1. Pick a user, gesture, and repetition triple that exists in the
   ``landmarks/original`` CSV files.
2. Display the pose sequence for the selected sample alongside its flipped,
   slowed, and speed-up counterparts.
3. Scrub through frames with a slider and quickly jump back to the selection
   screen (arrow keys are also supported for stepping through frames).

The four variants are rendered on the same screen using Matplotlib together with
the original video loaded from the dataset directory, giving a side-by-side
overview of how the augmentations alter the trajectory of the captured joints.
"""

